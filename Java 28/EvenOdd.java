public class EvenOdd {
    public static void main(String[] args) {

        int num = 10; // Number to check

        if (num % 2 == 0) {
            System.out.println(num + " is an Even Number"); // If divisible by 2
        } else {
            System.out.println(num + " is an Odd Number"); // If not divisible by 2
        }
    }
}
